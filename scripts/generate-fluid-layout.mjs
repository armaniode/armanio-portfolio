import fs from 'node:fs';
import postcss from 'postcss';
import { fluidValue } from './fluid-values.mjs';
const root = postcss.parse(fs.readFileSync('src/source-layout.css', 'utf8'));
root.walkAtRules('media', rule => {
  // Keep the wide-desktop artwork variant; replace stepped desktop sizing.
  if (/^\(min-width:\s*1512px\)$/.test(rule.params)) rule.replaceWith(...rule.nodes);
  else rule.remove();
});
root.walkDecls(decl => {
  if (decl.parent.type === 'atrule' && decl.parent.name === 'font-face') return;
  decl.value = fluidValue(decl.value, decl.prop);
});
fs.writeFileSync('src/fluid-layout.css', '/* Generated by scripts/generate-fluid-layout.mjs; edit source-layout.css or the generator. */\n' + root.toString());
